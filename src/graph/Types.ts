/**
 * The id declarations that type `annotate`: every node a spec or annotation
 * declares, mapped to its kind, as an augmentation of `sdp/annotations`.
 * Written by `sdp types`; `sdp check` reports `types-stale` when the graph has
 * moved on. Scenarios and code nodes are left out — annotations point at specs.
 */
import { annotate } from "sdp/annotations"
import type { Project } from "./Build.ts"

annotate(import.meta, { is: "ARCH-code-annotations" })

const omitted = new Set(["scenario", "code", "missing"])

export const idsDeclaration = (project: Project): string => {
  const ids = [...project.graph.nodes.values()]
    .filter((node) => !omitted.has(node.kind))
    .sort((a, b) => a.id.localeCompare(b.id))
  return [
    "// Generated by `sdp types` from the specification graph; run it again after adding or renaming specs.",
    "// It types the ids `annotate` accepts (see sdp/annotations). Do not edit by hand.",
    "",
    "declare module \"sdp/annotations\" {",
    "  interface Ids {",
    ...ids.map((node) => `    ${JSON.stringify(node.id)}: ${JSON.stringify(node.kind)}`),
    "  }",
    "}",
    "",
    "export {}",
    ""
  ].join("\n")
}
